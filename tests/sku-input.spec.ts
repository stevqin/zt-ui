import { afterEach, describe, expect, it } from 'vitest'
import { flushPromises, mount } from '@vue/test-utils'
import { defineComponent, h, nextTick, reactive } from 'vue'
import Form from '../src/components/form/ZtForm.vue'
import FormItem from '../src/components/form/ZtFormItem.vue'
import SkuInput from '../src/components/sku-input/ZtSkuInput.vue'
import type { ZtSkuProduct } from '../src/components/sku-select/types'
const product: ZtSkuProduct = { product_no: 'P01', product_name: '基础短袖', skcs: [
  { skc: 'RED', color_name: '红色', color_code: '023', skus: [{ sku: 'R-S', size_code: 'S' }, { sku: 'R-M', size_code: 'M', disabled: true }, { sku: 'R-L', size_code: 'L' }] },
  { skc: 'BLACK', color_name: '黑色', color_code: '000', skus: [{ sku: 'B-S', size_code: 'S' }, { sku: 'B-L', size_code: 'L' }] },
  { skc: 'GRAY', color_name: '灰色', disabled: true, skus: [{ sku: 'G-S', size_code: 'S' }] },
] }
const input = (w: ReturnType<typeof mount>, sku: string) => w.get(`[data-sku="${sku}"] input`)
afterEach(() => { document.body.innerHTML = '' })
describe('SKU quantity matrix', () => {
  it.each([':show-product-info="false"', ':showProductInfo="false"'])('accepts a bound Boolean false in component code: %s', (binding) => {
    const component = defineComponent({ components: { SkuInput }, setup: () => ({ product }), template: `<SkuInput :product="product" ${binding} />` })
    const w = mount(component)
    expect(w.find('.zt-sku-input__header').exists()).toBe(false)
    expect(w.find('.zt-sku-input__table').exists()).toBe(true)
    expect(w.find('input[placeholder]').exists()).toBe(false)
    w.unmount()
  })
  it('hides all product information without hiding the matrix or changing quantities', async () => {
    const w = mount(SkuInput, { props: { product } })
    await input(w, 'R-S').setValue('3')
    expect(w.find('.zt-sku-input__header').exists()).toBe(true)
    const changes = w.emitted('change')!.length
    await w.setProps({ showProductInfo: false })
    expect(w.find('.zt-sku-input__header').exists()).toBe(false)
    expect(w.find('table').exists()).toBe(true)
    expect((input(w, 'R-S').element as HTMLInputElement).value).toBe('3')
    expect(w.emitted('change')).toHaveLength(changes)
    await w.setProps({ showProductInfo: true })
    expect(w.find('.zt-sku-input__header').exists()).toBe(true)
    w.unmount()
  })
  it('ignores malformed external quantities and treats a zero limit as an empty quantity map', async () => {
    const w = mount(SkuInput, { props: { product, max: 0, modelValue: { 'R-S': 4, 'B-S': -1, 'B-L': 1.5, 'R-L': Number.NaN } } })
    expect(w.get('[data-total]').text()).toContain('0')
    await input(w, 'R-S').setValue('0')
    expect(w.emitted('change')).toBeUndefined()
    await w.setProps({ max: 10 })
    expect(w.get('[data-total]').text()).toContain('4')
  })
  it('does not erase or publish composing text and commits after composition ends', async () => {
    const w = mount(SkuInput, { props: { product } })
    const field = input(w, 'R-S')
    await field.trigger('compositionstart')
    ;(field.element as HTMLInputElement).value = '2'
    await field.trigger('input', { isComposing: true })
    expect(w.emitted('change')).toBeUndefined()
    expect((field.element as HTMLInputElement).value).toBe('2')
    await field.trigger('compositionend')
    expect(w.emitted('update:modelValue')?.[0]).toEqual([{ 'R-S': 2 }])
  })
  it('validates pasted quantities through FormItem and inherits form disabled state', async () => {
    const model = reactive({ quantities: {} as Record<string, number> })
    const w = mount(Form, { props: { model, rules: { quantities: { trigger: 'change', validator: (_rule: unknown, value: Record<string, number>) => Object.keys(value).length ? undefined : '请录入数量' } } }, slots: { default: () => h(FormItem, { prop: 'quantities' }, () => h(SkuInput, { product, modelValue: model.quantities, 'onUpdate:modelValue': (value: Record<string, number>) => { model.quantities = value } })) } })
    await expect((w.vm as any).validate()).rejects.toBeDefined()
    await flushPromises()
    expect(w.find('.zt-form-item.is-error').exists()).toBe(true)
    await input(w, 'R-S').trigger('paste', { clipboardData: { getData: () => '2' } })
    await flushPromises()
    expect(w.find('.zt-form-item.is-error').exists()).toBe(false)
    await w.setProps({ disabled: true })
    await input(w, 'R-S').trigger('paste', { clipboardData: { getData: () => '5' } })
    expect(model.quantities['R-S']).toBe(2)
    const ids = w.findAll('input').map(field => field.attributes('id'))
    expect(new Set(ids).size).toBe(ids.length)
    w.unmount()
  })
  it('unions size columns, shows business color codes and distinguishes missing combinations', () => {
    const w = mount(SkuInput, { props: { product } })
    expect(w.findAll('thead th[data-size]').map(x => x.text())).toEqual(['S', 'M', 'L'])
    expect(w.text()).toContain('红色')
    expect(w.text()).toContain('023')
    expect(w.find('[data-row="1"][data-col="1"] input').exists()).toBe(false)
    expect(w.emitted('update:modelValue')).toBeUndefined()
  })
  it('honors explicit size order without losing remaining sizes', () => {
    const w = mount(SkuInput, { props: { product, sizeOrder: ['L', 'S'] } })
    expect(w.findAll('thead th[data-size]').map(x => x.text())).toEqual(['L', 'S', 'M'])
  })
  it('updates quantities immutably and returns original business objects and totals', async () => {
    const initial = Object.freeze({ 'B-S': 2 })
    const w = mount(SkuInput, { props: { product, modelValue: initial } })
    await input(w, 'R-S').setValue('5')
    expect(w.emitted('update:modelValue')?.[0]).toEqual([{ 'B-S': 2, 'R-S': 5 }])
    const change = w.emitted('change')![0][0] as any
    expect(change.totalQuantity).toBe(7)
    expect(change.skuCount).toBe(2)
    expect(change.entries.find((x: any) => x.sku.sku === 'R-S')).toEqual({ spu: product, skc: product.skcs[0], sku: product.skcs[0].skus[0], quantity: 5 })
    expect(initial).toEqual({ 'B-S': 2 })
    expect((input(w, 'R-S').element as HTMLInputElement).value).toBe('')
  })
  it('uses internal state when uncontrolled and clears zero or empty quantities', async () => {
    const w = mount(SkuInput, { props: { product } })
    await input(w, 'R-S').setValue('4')
    expect(w.get('[data-total]').text()).toContain('4')
    await input(w, 'R-S').setValue('0')
    expect(w.emitted('update:modelValue')?.at(-1)).toEqual([{}])
    await input(w, 'B-L').setValue('3')
    await input(w, 'B-L').setValue('')
    expect(w.emitted('update:modelValue')?.at(-1)).toEqual([{}])
  })
  it('rejects negative, decimal and nonnumeric quantities and clamps the upper bound', async () => {
    const w = mount(SkuInput, { props: { product, max: 20 } })
    for (const value of ['-1', '1.2', 'abc', '1e2']) await input(w, 'R-S').setValue(value)
    expect(w.emitted('update:modelValue')).toBeUndefined()
    await input(w, 'R-S').setValue('999999999999999999999999')
    expect(w.emitted('update:modelValue')?.at(-1)).toEqual([{ 'R-S': 20 }])
    expect((input(w, 'R-S').element as HTMLInputElement).value).toBe('20')
  })
  it('blocks disabled SKCs, individual SKUs, readonly and disabled panels', async () => {
    const w = mount(SkuInput, { props: { product } })
    expect(input(w, 'R-M').attributes('disabled')).toBeDefined()
    expect(input(w, 'G-S').attributes('disabled')).toBeDefined()
    await input(w, 'R-M').setValue('5')
    expect(w.emitted('update:modelValue')).toBeUndefined()
    await w.setProps({ readonly: true })
    await input(w, 'R-S').setValue('5')
    expect(w.emitted('update:modelValue')).toBeUndefined()
    await w.setProps({ readonly: false, disabled: true })
    expect(input(w, 'R-S').attributes('disabled')).toBeDefined()
  })
  it('reflects external updates silently and removes unknown keys from derived totals', async () => {
    const w = mount(SkuInput, { props: { product, modelValue: { 'R-S': 2, unknown: 88, 'G-S': 3 } } })
    expect(w.get('[data-total]').text()).toContain('5')
    await w.setProps({ modelValue: { 'B-L': 8 } })
    expect((input(w, 'B-L').element as HTMLInputElement).value).toBe('8')
    expect(w.emitted('change')).toBeUndefined()
    await w.setProps({ product: { spu: 'OTHER', skcs: [] } })
    expect(w.text()).toContain('暂无可录入规格')
    expect(w.emitted('change')).toBeUndefined()
  })
  it('moves Enter in row order and vertical arrows in the same column, skipping disabled cells', async () => {
    const w = mount(SkuInput, { props: { product }, attachTo: document.body })
    input(w, 'R-S').element.focus()
    await input(w, 'R-S').trigger('keydown', { key: 'Enter' })
    expect(document.activeElement).toBe(input(w, 'R-L').element)
    await input(w, 'R-L').trigger('keydown', { key: 'ArrowDown' })
    expect(document.activeElement).toBe(input(w, 'B-L').element)
    await input(w, 'B-L').trigger('keydown', { key: 'Enter', shiftKey: true })
    expect(document.activeElement).toBe(input(w, 'B-S').element)
    w.unmount()
  })
  it('pastes an Excel rectangle without shifting missing or disabled coordinates', async () => {
    const w = mount(SkuInput, { props: { product, modelValue: { 'R-M': 7, 'B-L': 9 } } })
    await input(w, 'R-S').trigger('paste', { clipboardData: { getData: () => '2\t3\t4\r\n5\t6\t0\r\n7\t8\t9\r\n' } })
    expect(w.emitted('update:modelValue')).toEqual([[{ 'R-S': 2, 'R-M': 7, 'R-L': 4, 'B-S': 5 }]])
    expect(w.emitted('change')).toHaveLength(1)
  })
  it('ignores invalid paste cells and keeps other quantities', async () => {
    const w = mount(SkuInput, { props: { product, modelValue: { 'R-S': 3, 'R-L': 4 } } })
    await input(w, 'R-S').trigger('paste', { clipboardData: { getData: () => 'bad\t2\t' } })
    expect(w.emitted('update:modelValue')?.[0]).toEqual([{ 'R-S': 3 }])
  })
  it('exposes focus and respects explicit size and summary visibility', async () => {
    const w = mount(SkuInput, { props: { product, size: 'mini', showSummary: false }, attachTo: document.body })
    expect(w.classes()).toContain('zt-sku-input--mini')
    expect(w.find('tfoot').exists()).toBe(false)
    expect((w.vm as any).focus('R-M')).toBe(false)
    expect((w.vm as any).focus('B-S')).toBe(true)
    await nextTick()
    expect(document.activeElement).toBe(input(w, 'B-S').element)
    w.unmount()
  })
})
