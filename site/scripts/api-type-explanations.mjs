function parsedMembers(type) {
  const file = ts.createSourceFile('api-type.ts', type, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  const declaration = file.statements.find(node => ts.isInterfaceDeclaration(node) || ts.isTypeAliasDeclaration(node));
  const members = declaration && ts.isInterfaceDeclaration(declaration) ? declaration.members : [];
  return members.flatMap(member => member.name && (ts.isIdentifier(member.name) || ts.isStringLiteral(member.name)) ? [member.name.text] : []);
}
export function typeDescription(component, name, type) {
  if (explanations[name]) return explanations[name];
  const base = name.replace(/(?:Props|Instance|Emits|Status|Size)$/, '');
  const label = labels[base.replace(/^Zt/, '')];
  if (name.endsWith('Props') && label) {
    const members = parsedMembers(type).slice(0, 5);
    const details = members.map(key => fields[key] ? `${fields[key]}（${key}）` : key).join('、');
    return `${label}的输入参数结构${details ? `，包含${details}` : ''}。`;
  }
  if (name.endsWith('Instance') && instances[base]) return instances[base];
  if (name.endsWith('Emits') && label) return `${label}事件的回调签名，定义事件名称及其携带参数。`;
  if (name.endsWith('Status') && label) {
    const values = [...type.matchAll(/'([^']+)'/g)].map(match => match[1]);
    const meaning = { default: '默认', primary: '主要', success: '成功', warning: '警告', danger: '危险', info: '说明', error: '错误' };
    return `${label}的视觉状态取值${values.length ? `：${values.map(value => `${value}（${meaning[value] ?? value}）`).join('、')}` : ''}。`;
  }
  if (name.endsWith('Size') && (label || name === 'ZtComponentSize')) return `${label ?? '组件全局'}的五档预设尺寸：mini、small、default、medium、large。`;
}
