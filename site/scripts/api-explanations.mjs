export function propExplanation(component, name) {
  if (name === 'size' && component === 'ZtIcon') return '图标尺寸，支持数字像素值或 CSS 长度。'
  if (name === 'size' && component === 'ZtAvatar') return '头像尺寸，支持预设档位、数字像素值或 CSS 长度。'
  return propDescription(component, name) ?? props[name]
}
