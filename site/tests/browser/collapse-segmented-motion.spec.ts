import { expect, test } from '@playwright/test'

test('Segmented moves and resizes one capsule without scaling labels and follows responsive layout', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/#/components/segmented')
  const group = page.getByRole('radiogroup', { name: '统计周期' })
  const indicator = group.locator('.zt-segmented__indicator')
  await expect(indicator).toHaveClass(/is-animated/)
  const target = group.getByRole('radio', { name: '月', exact: true })
  await target.evaluate(el => { (el as HTMLElement).style.paddingInline = '46px' })
  const before = await indicator.boundingBox()
  const labelBefore = await target.locator('span').boundingBox()
  const destination = await target.boundingBox()
  await target.click()
  const midway = await indicator.evaluate(async el => {
    await new Promise(requestAnimationFrame)
    const animations = el.getAnimations()
    for (const animation of animations) { animation.pause(); animation.currentTime = 110 }
    const box = el.getBoundingClientRect()
    return { count: animations.length, x: box.x, width: box.width }
  })
  expect(midway.count).toBeGreaterThanOrEqual(2)
  expect(midway.x).toBeGreaterThan(before!.x)
  expect(midway.x).toBeLessThan(destination!.x)
  expect(midway.width).toBeGreaterThan(before!.width)
  expect(midway.width).toBeLessThan(destination!.width)
  expect((await target.locator('span').boundingBox())!.width).toBeCloseTo(labelBefore!.width, 1)
  await indicator.evaluate(el => el.getAnimations().forEach(animation => animation.finish()))
  await expect.poll(async () => Math.abs((await indicator.boundingBox())!.x - (await target.boundingBox())!.x)).toBeLessThan(1)
  await expect.poll(async () => Math.abs((await indicator.boundingBox())!.width - (await target.boundingBox())!.width)).toBeLessThan(1)
  await expect(group.locator('.zt-segmented__indicator')).toHaveCount(1)
  const block = page.getByRole('radiogroup', { name: '商品展示方式' })
  await block.getByRole('radio', { name: '列表' }).click()
  await block.evaluate(el => { (el as HTMLElement).style.width = '360px' })
  await expect.poll(async () => Math.abs((await block.locator('.zt-segmented__indicator').boundingBox())!.width - (await block.getByRole('radio', { name: '列表' }).boundingBox())!.width)).toBeLessThan(1)
  await page.setViewportSize({ width: 390, height: 1000 })
  await expect.poll(async () => Math.abs((await block.locator('.zt-segmented__indicator').boundingBox())!.x - (await block.getByRole('radio', { name: '列表' }).boundingBox())!.x)).toBeLessThan(1)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await group.getByRole('radio', { name: '日', exact: true }).click()
  await expect(indicator).toHaveCSS('transition', 'none')
  expect(await indicator.evaluate(el => el.getAnimations().length)).toBe(0)
})

test('Collapse uses a consistent disclosure chevron that rotates a quarter turn', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/#/components/collapse')
  const header = page.getByRole('button', { name: '如何导出报表？', exact: true })
  const arrow = header.locator('.zt-collapse-item__arrow')
  await expect(arrow.locator('path')).toHaveAttribute('d', 'm9 6 6 6-6 6')
  await expect(arrow).toHaveCSS('width', '16px')
  await header.click()
  await expect(header).toHaveAttribute('aria-expanded', 'true')
  await expect(arrow).toHaveCSS('transform', 'matrix(0, 1, -1, 0, 0, 0)')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(arrow).toHaveCSS('transition', 'none')
})
